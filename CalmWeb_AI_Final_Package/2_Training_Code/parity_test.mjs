import fs from 'fs';
globalThis.CalmWeb = {};
globalThis.chrome = { runtime: { getURL: (p) => '/home/claude/calmweb-extension/' + p } };
globalThis.fetch = async (p) => ({ json: async () => JSON.parse(fs.readFileSync(p, 'utf8')) });
await import('/home/claude/calmweb-extension/content/ai-model.js');
await CalmWeb.loadModel();
const { text, proba } = JSON.parse(fs.readFileSync('results/parity.json', 'utf8'));
let maxDiff = 0, sameLabel = 0;
text.forEach((t, i) => { const p = CalmWeb.promoScore(t); maxDiff = Math.max(maxDiff, Math.abs(p - proba[i])); if ((p >= 0.5) === (proba[i] >= 0.5)) sameLabel++; });
console.log(`parity: ${text.length} texts, same decision ${sameLabel}/${text.length}, largest probability difference ${maxDiff.toFixed(5)}`);
